def band_edge(VSO: float, t: float = T_HOP) -> float:
    """max_k |eps_s(k)| = 4t sqrt(1 + V_SO^2/(2t^2));  reached at (pi,0)-type points."""
    return 4.0 * t * np.sqrt(1.0 + (VSO / t) ** 2 / 2.0)


def kgrid(Nk: int):
    """Midpoint grid over the quarter zone [0,pi]^2 (the full zone is generated by the symmetries)."""
    k = (np.arange(Nk) + 0.5) * np.pi / Nk
    kx = k[:, None]
    ky = k[None, :]
    e0 = -2.0 * T_HOP * (np.cos(kx) + np.cos(ky))
    R = np.sqrt(np.sin(kx) ** 2 + np.sin(ky) ** 2)
    return e0, R


